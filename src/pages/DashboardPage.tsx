import { useEffect, useState } from 'react';
import { Alert } from '../components/Alert';
import { Card } from '../components/Card';
import { getGreetingRequest } from '../services/dashboard.service';
import type { Greeting } from '../types/dashboard';
import { parseApiError } from '../utils/api-error';

export function DashboardPage() {
  const [greeting, setGreeting] = useState<Greeting | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [isLoading, setIsLoading] = useState(true);
  const [reloadKey, setReloadKey] = useState(0);

  useEffect(() => {
    let cancelled = false;

    getGreetingRequest()
      .then((result) => {
        if (cancelled) return;
        setGreeting(result);
        setError(null);
      })
      .catch((requestError: unknown) => {
        if (cancelled) return;
        setError(parseApiError(requestError).message);
      })
      .finally(() => {
        if (!cancelled) setIsLoading(false);
      });

    return () => {
      cancelled = true;
    };
  }, [reloadKey]);

  const handleRefresh = () => {
    setIsLoading(true);
    setReloadKey((key) => key + 1);
  };

  return (
    <Card title="Dashboard">
      {error && <Alert variant="error">{error}</Alert>}

      {isLoading ? (
        <p role="status" className="text-gray-600">
          Preparing your personalized message...
        </p>
      ) : (
        greeting && (
          <div aria-live="polite">
            <p className="text-lg font-medium">{greeting.greeting}</p>
            <p className="mt-2 text-gray-700">{greeting.tip}</p>
            <p className="mt-3 text-xs text-gray-500">
              {greeting.source === 'ai'
                ? 'Generated by AI'
                : 'Standard message (AI is unavailable right now)'}
            </p>
          </div>
        )
      )}

      <button
        type="button"
        onClick={handleRefresh}
        disabled={isLoading}
        className="mt-4 rounded border border-gray-300 px-3 py-1 text-sm hover:bg-gray-100 disabled:opacity-60"
      >
        New message
      </button>
    </Card>
  );
}